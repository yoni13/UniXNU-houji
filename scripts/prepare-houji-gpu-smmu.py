#!/usr/bin/env python3
"""houji GPU SMMU inputs for UniXNU Adreno740, ported from UniXNU-sheng scripts/prepare-sheng-gpu-smmu.py: the Qualcomm Adreno
context bank policy from Linux drivers/iommu/arm/arm-smmu/arm-smmu-qcom.c and the SMMU range and GPU/GMU streams from this phone's
mainline DTB (adreno_smmu at 0x3da0000; gpu iommus streams 0 and 1, gmu stream 5). Source and DT only, no hardware read.
Usage: prepare-houji-gpu-smmu.py LINUX_SOURCE_DIR DTB OUT"""
import hashlib, json, subprocess, sys
from pathlib import Path


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    cache, dtb, out = (Path(a) for a in sys.argv[1:4])
    source = cache / 'drivers/iommu/arm/arm-smmu/arm-smmu-qcom.c'
    text = source.read_text()
    start = text.index('static int qcom_adreno_smmu_alloc_context_bank(')
    body = text[start:text.index('static bool qcom_adreno_can_do_ttbr1(', start)]
    if not all(s in body for s in ['start = 0;', 'count = 1;', 'start = 1;', 'count = smmu->num_context_banks;']):
        raise SystemExit('Context ownership policy changed')
    if 'reg |= ARM_SMMU_SCTLR_HUPCF;' not in text:
        raise SystemExit('Adreno fault continuation policy changed')

    def cells(node, name):
        return [int(v, 16) for v in subprocess.check_output(['fdtget', '-t', 'x', str(dtb), node, name], text=True).split()]

    smmu = '/soc@0/iommu@3da0000'
    compatible = subprocess.check_output(['fdtget', '-t', 's', str(dtb), smmu, 'compatible'], text=True).split()
    if 'qcom,adreno-smmu' not in compatible:
        raise SystemExit('Adreno SMMU node binding differs')
    reg = cells(smmu, 'reg')
    if len(reg) != 4:
        raise SystemExit('SMMU range format differs')
    region = dict(base=(reg[0] << 32) | reg[1], bytes=(reg[2] << 32) | reg[3])
    phandle = cells(smmu, 'phandle')[0]
    iommu_cells = cells(smmu, '#iommu-cells')[0]

    def streams(node):
        v = cells(node, 'iommus')
        entries = [v[i:i + 1 + iommu_cells] for i in range(0, len(v), 1 + iommu_cells)]
        if any(e[0] != phandle for e in entries):
            raise SystemExit('Stream not on the Adreno SMMU: ' + node)
        return [e[1] for e in entries]

    gpu, gmu = streams('/soc@0/gpu@3d00000'), streams('/soc@0/gmu@3d6a000')
    if gpu != [0, 1] or gmu != [5]:
        raise SystemExit('Stream binding changed: gpu %r gmu %r' % (gpu, gmu))
    out.mkdir(parents=True, exist_ok=True)
    header = out / 'ShengGpuSmmuSource.h'
    header.write_text('/* Generated by prepare-houji-gpu-smmu.py: pinned source/DT policy, not observed hardware. */\n#include <stdint.h>\n' +
                      '#define SHENG_GPU_SMMU_BASE UINT64_C(' + hex(region['base']) + ')\n#define SHENG_GPU_SMMU_BYTES ' +
                      str(region['bytes']) + 'u\n#define SHENG_GPU_SMMU_GPU_STREAMS 2u\n#define SHENG_GPU_SMMU_GMU_SID 5u\n' +
                      'static const uint16_t sheng_gpu_smmu_sids[2]={0,1};\n')
    report = dict(qcom_source_sha256=sha(source), dtb_sha256=sha(dtb), header_sha256=sha(header), gpu_context_bank=0,
                  gmu_context_bank_min=1, gpu_sids=gpu, gmu_sid=gmu[0], register_range=region, hardware_observed=False)
    (out / 'smmu-source-report.json').write_text(json.dumps(report, indent=2) + '\n')
    print('PASS: Adreno SMMU %s + %#x, GPU streams %s on bank 0, GMU stream %d on banks >= 1' % (
        hex(region['base']), region['bytes'], gpu, gmu[0]))


if __name__ == '__main__':
    main()
