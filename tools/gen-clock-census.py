#!/usr/bin/env python3
"""Generate kernel/overlay/iokit/Kernel/arm/HoujiClockCensus.h: the register offsets and names of the SM8650 clock controllers'
branches, root clock generators, PLLs and power domains (GDSCs), read from Linux's clock drivers (v6.12: gcc-sm8650.c,
gpucc-sm8650.c, dispcc-sm8550.c, which also serves SM8650). Only offsets and names are taken; the census reads these registers
and writes none.

usage: gen-clock-census.py DIR_WITH_LINUX_FILES OUTPUT.h
"""
import re
import sys

SOURCES = [('gcc', 'gcc-sm8650.c', 0x100000, 0x1f4200), ('gpucc', 'gpucc-sm8650.c', 0x3d90000, 0xa000),
           ('dispcc', 'dispcc-sm8550.c', 0xaf00000, 0x20000)]


def blocks(text, kind):
    for m in re.finditer(r'^static struct %s (\w+) = \{\n(.*?)^\};' % kind, text, re.S | re.M):
        yield m.group(1), m.group(2)


def field(body, name):
    m = re.search(r'\.%s = (0x[0-9a-f]+)' % name, body)
    return int(m.group(1), 16) if m else None


def short(name, prefix):
    for p in (prefix + '_', 'gpu_cc_', 'disp_cc_'):
        if name.startswith(p):
            name = name[len(p):]
    return re.sub(r'_clk$', '', name)


def main():
    directory, output = sys.argv[1], sys.argv[2]
    out = ['/* SPDX-License-Identifier: GPL-2.0-only',
           ' * Generated by tools/gen-clock-census.py from Linux v6.12 drivers/clk/qcom (gcc-sm8650.c, gpucc-sm8650.c, dispcc-sm8550.c):',
           ' * register offsets and names only. Kinds: B branch (halt register; bit 31 set = off), R root clock generator (command',
           ' * register; bit 31 set = root off; configuration at +4), P PLL (mode register), G power domain (GDSCR; bit 31 set = on). */',
           '#pragma once', 'struct HoujiCensusEntry {char kind; unsigned char block; unsigned offset; const char *name;};',
           'struct HoujiCensusBlock {const char *name; unsigned long long base; unsigned size;};',
           'static const HoujiCensusBlock houjiCensusBlocks[] = {']
    for name, _, base, size in SOURCES:
        out.append('    {"%s", 0x%xULL, 0x%x},' % (name, base, size))
    out += ['};', 'static const HoujiCensusEntry houjiCensus[] = {']
    for index, (prefix, filename, _, size) in enumerate(SOURCES):
        text = open('%s/%s' % (directory, filename)).read()
        rows = []
        for name, body in blocks(text, 'clk_branch'):
            rows.append(('B', field(body, 'halt_reg'), name))
        for name, body in blocks(text, 'clk_rcg2'):
            rows.append(('R', field(body, 'cmd_rcgr'), name))
        for name, body in blocks(text, 'clk_alpha_pll'):
            rows.append(('P', field(body, 'offset'), name))
        for name, body in blocks(text, 'gdsc'):
            rows.append(('G', field(body, 'gdscr'), name))
        for kind, offset, name in sorted(rows, key=lambda r: (r[0], r[1] if r[1] is not None else -1)):
            if offset is None:   # a branch with only a vote bit (no halt register): its state shows in its parent's users
                continue
            if offset + 8 > size:
                raise SystemExit('%s: %s is outside the block' % (filename, name))
            out.append("    {'%s', %u, 0x%x, \"%s\"}," % (kind, index, offset, short(name, prefix)))
    out.append('};')
    open(output, 'w').write('\n'.join(out) + '\n')
    print('%u entries' % (len(out) - 14))


main()
